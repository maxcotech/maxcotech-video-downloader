"""YouTube-side logic without touching YouTube: link recognition, quality choice,
and the download -> join (video + audio) / MP3 pipeline against a local server
serving clips generated by FFmpeg."""
import importlib.util, json, re, subprocess, sys, threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
APP = Path(sys.argv[1]); WORK = Path(sys.argv[2])
spec = importlib.util.spec_from_file_location("zd", APP)
zd = importlib.util.module_from_spec(spec); sys.modules["zd"] = zd; spec.loader.exec_module(zd)
WORK.mkdir(parents=True, exist_ok=True)
for f in WORK.glob("*"):
    f.unlink()

# ---- link recognition -------------------------------------------------------
yt = {
    "https://www.youtube.com/watch?v=aqz-KE-bpKQ": (True, True),
    "https://youtu.be/aqz-KE-bpKQ?t=10": (True, True),
    "https://www.youtube.com/shorts/abcDEF12345": (True, True),
    "https://m.youtube.com/watch?v=abc&list=PL123": (True, True),   # video inside a playlist = that video
    "https://www.youtube.com/playlist?list=PL123": (True, False),
    "https://www.youtube.com/@SomeChannel/videos": (True, False),
    "https://music.youtube.com/watch?v=abc": (True, True),
    "https://us06web.zoom.us/rec/share/abc": (False, None),
}
for url, (is_yt, single) in yt.items():
    assert zd.is_youtube(url) == is_yt, url
    if is_yt:
        assert zd.is_youtube_single(url) == single, url
print("link recognition: OK")

assert zd.quality_opts("Best")["format_sort"] == ["res", "vcodec:h264", "ext:mp4:m4a"]
assert zd.quality_opts("720p")["format_sort"][0] == "res:720"
assert zd.quality_opts("Audio only (MP3)")["format"].startswith("ba")
print("quality options: OK")

items = zd.parse_links("check these out https://youtu.be/aaa111 and\nhttps://www.youtube.com/watch?v=bbb222&t=5s\n")
assert [i["url"] for i in items] == ["https://youtu.be/aaa111", "https://www.youtube.com/watch?v=bbb222&t=5s"], items
print("parse YouTube links in text: OK")

# ---- tools ------------------------------------------------------------------
ff = zd.tool_path("ffmpeg"); deno = zd.tool_path("deno")
print("ffmpeg:", ff); print("deno:", deno)
assert ff and deno
ffprobe = ff.with_name("ffprobe.exe")

# make a 6 s video-only MP4 and audio-only M4A, like YouTube's separate streams
v = WORK / "src_video.mp4"; a = WORK / "src_audio.m4a"
subprocess.run([str(ff), "-y", "-loglevel", "error", "-f", "lavfi", "-i", "testsrc=size=640x360:rate=25",
                "-t", "6", "-c:v", "mpeg4", "-q:v", "3", "-an", str(v)], check=True)
subprocess.run([str(ff), "-y", "-loglevel", "error", "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=44100",
                "-t", "6", "-c:a", "aac", "-b:a", "128k", "-vn", str(a)], check=True)
FILES = {"/v.mp4": v.read_bytes(), "/a.m4a": a.read_bytes(), "/big.bin": bytes(range(256)) * (48 * 1024)}


class H(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    def log_message(self, *x): pass
    def do_GET(self):
        data = FILES[self.path]
        rng = self.headers.get("Range")
        if rng:
            s, e = map(int, re.match(r"bytes=(\d+)-(\d+)", rng).groups()); e = min(e, len(data) - 1)
            body = data[s:e + 1]; self.send_response(206)
            self.send_header("Content-Range", f"bytes {s}-{e}/{len(data)}")
        else:
            body = data; self.send_response(200)
        self.send_header("Content-Length", str(len(body))); self.end_headers()
        try:
            self.wfile.write(body)
        except OSError:
            pass


srv = ThreadingHTTPServer(("127.0.0.1", 0), H); srv.daemon_threads = True
threading.Thread(target=srv.serve_forever, daemon=True).start()
base = f"http://127.0.0.1:{srv.server_port}"


def part(path, ext):
    return {"url": base + path, "headers": {}, "ext": ext, "filesize": len(FILES[path]),
            "max_chunk": 64 * 1024, "http": True}


class J:  # minimal stand-in for a Job
    done = total = 0; state = detail = ""


def streams(p):
    out = subprocess.run([str(ffprobe), "-v", "error", "-show_entries", "stream=codec_type",
                          "-of", "json", str(p)], capture_output=True, text=True, check=True).stdout
    return sorted(s["codec_type"] for s in json.loads(out)["streams"])


# join video + audio
t = {"title": "x", "ext": "mp4", "post": "merge", "parts": [part("/v.mp4", "mp4"), part("/a.m4a", "m4a")]}
dest = WORK / "Joined.mp4"
j = J()
zd.download_target(t, dest, [], 8, j, threading.Event())
assert streams(dest) == ["audio", "video"], streams(dest)
assert not list(WORK.glob("Joined.mp4.*")), list(WORK.glob("Joined.mp4.*"))
assert j.done == j.total == dest.stat().st_size
print(f"join video+audio: OK ({dest.stat().st_size // 1024} KB, temp pieces cleaned up)")

# audio only -> MP3
t = {"title": "x", "ext": "mp3", "post": "mp3", "parts": [part("/a.m4a", "m4a")]}
dest = WORK / "Song.mp3"
zd.download_target(t, dest, [], 8, J(), threading.Event())
assert streams(dest) == ["audio"]
out = subprocess.run([str(ffprobe), "-v", "error", "-show_entries", "stream=codec_name", "-of", "csv=p=0",
                      str(dest)], capture_output=True, text=True).stdout.strip()
assert out == "mp3", out
print("audio only -> MP3: OK")

# resume: video piece already finished before a pause is not downloaded again
t = {"title": "x", "ext": "mp4", "post": "merge", "parts": [part("/v.mp4", "mp4"), part("/a.m4a", "m4a")]}
dest = WORK / "Resumed.mp4"
(WORK / "Resumed.mp4.p0.mp4").write_bytes(FILES["/v.mp4"])
hits = []
orig = zd.SegmentedDownloader.run
def spy(self):
    hits.append(self.url)
    return orig(self)
zd.SegmentedDownloader.run = spy
zd.download_target(t, dest, [], 8, J(), threading.Event())
zd.SegmentedDownloader.run = orig
assert hits == [base + "/a.m4a"], hits
assert streams(dest) == ["audio", "video"]
print("resume after pause (skips finished piece): OK")

# chunk cap honoured (YouTube throttles big range requests)
d = zd.SegmentedDownloader(base + "/big.bin", WORK / "cap.bin", {}, [], 4, max_chunk=2 * 1024 * 1024)
d.run()
assert d.chunk == 2 * 1024 * 1024, d.chunk          # 12 MB file, capped at 2 MB pieces
assert (WORK / "cap.bin").read_bytes() == FILES["/big.bin"]
print("piece-size cap: OK")
print("ALL MEDIA TESTS PASSED")
